import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const dir = resolve(import.meta.dirname, '..', 'dist', 'client')
const raw = await readFile(resolve(dir, 'client.js'), 'utf8')

let css = ''
for (const file of await readdir(dir)) {
  if (file.endsWith('.css')) {
    css = await readFile(resolve(dir, file), 'utf8')
    break
  }
}

const wrapped = `/* @local/mo-reader client bundle (generated by scripts/wrap-client.mjs) */
(function () {
  if (typeof document === 'undefined') return;
  var css = ${JSON.stringify(css)};
  var existing = document.querySelector('style[data-dsh-plugin="mo-reader"]');
  if (existing) existing.remove();
  if (!css) return;
  var style = document.createElement('style');
  style.setAttribute('data-dsh-plugin', 'mo-reader');
  style.textContent = css;
  document.head.appendChild(style);
})();
window.__ModuleLoader__.load({
  id: '@local/mo-reader',
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${raw}
    })(module, exports, require);
    const out = module.exports;
    return out && out.default ? out.default : out;
  },
});
`

await writeFile(resolve(dir, 'client.js'), wrapped)
